  // Age in weeks from birth; month cards are turned into weeks so one set of age bands covers both.
  const weeks = (e) => e.week || Math.round(e.month * 4.35);

  // Typical numbers for her age: hours of sleep in 24 hours, naps, wet nappies and poos.
  function guide(e) {
    const wk = weeks(e);
    const hours = wk <= 2 ? '14–17 h, some up to 18 h' : wk <= 16 ? '14–17 h' : wk < 52 ? '12–16 h' : '11–14 h';
    const naps = wk <= 8 ? 'Round the clock, 1–4 h each' : wk <= 16 ? 'Several, still irregular' : wk <= 19 ? '3–4 a day'
      : wk <= 23 ? 'About 3 a day' : wk <= 28 ? '2–3 a day' : wk < 52 ? 'Usually 2 a day' : '1–2 a day';
    const wet = wk === 1 ? 'Building to 6+ a day' : '6 or more a day';
    const poo = wk === 1 ? '2+ a day, black then yellow' : wk <= 6 ? 'Several a day, often every feed'
      : wk < 26 ? 'Several a day to one every few days' : 'Around 2 a day on average';
    return { sleep: [['Sleep in 24 h', hours], ['Naps', naps]], nappies: [['Wet nappies', wet], ['Poos', poo]] };
  }
  // Only the numbers that are new on this card: everything on the first card, then whatever
  // differs from the card before. A part with nothing new has no boxes.
  function guideNew(e) {
    const i = ENTRIES.indexOf(e), now = guide(e), prev = i > 0 ? guide(ENTRIES[i - 1]) : null, out = {};
    for (const k of Object.keys(now)) {
      const fresh = now[k].filter(([label, v]) => !prev || prev[k].find((p) => p[0] === label)[1] !== v);
      if (fresh.length) out[k] = fresh;
    }
    return out;
  }
  function guideSources(e) {
    const wk = weeks(e);
    return { sleep: [wk <= 16 ? 'nsf' : 'aap', wk <= 8 ? 'sfNewborn' : wk >= 26 ? 'sf6mo' : 'sf4mo'] };
  }

  // The links behind one part of a card: the part's usual sources plus any the entry adds.
  function sourcesFor(entry, key) {
    const sec = SECTIONS.find((s) => s.key === key);
    const base = !sec ? [] : typeof sec.src === 'function' ? sec.src(entry) : sec.src;
    const keys = [...new Set([...base, ...((entry.src && entry.src[key]) || [])])];
    return keys.map((k) => ({ name: SOURCES[k][0], url: SOURCES[k][1] }));
  }

  const weekEntry = (n) => ENTRIES.find((e) => e.week === n) || null;
  const monthEntry = (n) => ENTRIES.find((e) => e.month === n) || null;

  // Weeks 1–26 (week 1 starts on the day she's born), then whole months from 7 to 12.
  function milestones(ageDays) {
    const week = Math.floor(ageDays / 7) + 1;
    if (week <= 26) return { now: weekEntry(week), next: week < 26 ? weekEntry(week + 1) : monthEntry(7) };
    const month = Math.min(12, Math.max(7, Math.floor(ageDays / 30.44)));
    return { now: monthEntry(month), next: month < 12 ? monthEntry(month + 1) : null };
  }

  const api = { ENTRIES, SECTIONS, SOURCES, sourcesFor, guide, guideNew, milestones };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.FeedMilestones = api;
